const originalTextNodes = [];
const originalAttributes = [];
const languageButton = document.createElement('button');
languageButton.type = 'button';
languageButton.className = 'language-toggle';
languageButton.setAttribute('aria-label', 'Switch page language');

function rememberPageText() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.nodeValue.trim()) originalTextNodes.push([node, node.nodeValue]);
  }

  document.querySelectorAll('[alt], [aria-label], [title]').forEach(element => {
    ['alt', 'aria-label', 'title'].forEach(attribute => {
      if (element.hasAttribute(attribute)) {
        originalAttributes.push([element, attribute, element.getAttribute(attribute)]);
      }
    });
  });
}

function switchLanguage(language) {
  const isHindi = language === 'hi';
  document.documentElement.lang = isHindi ? 'hi' : 'en';

  originalTextNodes.forEach(([node, original]) => {
    const leading = original.match(/^\s*/)[0];
    const trailing = original.match(/\s*$/)[0];
    const value = original.trim();
    const translated = isHindi ? hindiText[value] : undefined;
    node.nodeValue = translated ? `${leading}${translated}${trailing}` : original;
  });

  originalAttributes.forEach(([element, attribute, original]) => {
    const translated = isHindi ? hindiAttributes[original] || hindiText[original] : original;
    element.setAttribute(attribute, translated);
  });

  if (isHindi) {
    const translatedTitle = hindiText[document.title];
    if (translatedTitle) document.title = translatedTitle;
    const description = document.querySelector('meta[name="description"]');
    if (description) {
      description.content = hindiText[originalDescription]
        || "महिला शक्ति विकास फाउंडेशन के साथ महिलाओं और लड़कियों के लिए शिक्षा, कौशल, स्वास्थ्य-जागरूकता और आजीविका के अवसरों के बारे में जानें।";
    }
    languageButton.textContent = "English";
    languageButton.setAttribute('aria-label', 'Switch to English');
  } else {
    document.title = originalTitle;
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = originalDescription;
    languageButton.textContent = "हिन्दी";
    languageButton.setAttribute('aria-label', 'हिंदी में बदलें');
  }

  localStorage.setItem('msvf-language', language);
}

const originalTitle = document.title;
const originalDescription = document.querySelector('meta[name="description"]')?.content || '';
rememberPageText();
const navMenu = document.getElementById('navMenu');
if (navMenu) {
  languageButton.addEventListener('click', () => {
    switchLanguage(document.documentElement.lang === 'hi' ? 'en' : 'hi');
  });
  navMenu.insertBefore(languageButton, navMenu.querySelector('.nav-donate'));
}

switchLanguage(localStorage.getItem('msvf-language') || 'hi');
